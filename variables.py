# Модуль 1: Описание объекта "сотрудник"

# Характеристики сотрудника
name = "Иван Петров"  # строка - имя сотрудника
age = 35  # целое число - возраст
salary = 75000.50  # число с плавающей точкой - зарплата
is_manager = True  # логический тип - является ли руководителем
experience = 8  # целое число - стаж работы в годах
department = "IT-отдел"  # строка - отдел
rating = 4.75  # число с плавающей точкой - рейтинг сотрудника
has_bonus = False  # логический тип - есть ли премия

# Вывод типов переменных
print("Типы переменных:")
print(f"name: {type(name)}")
print(f"age: {type(age)}")
print(f"salary: {type(salary)}")
print(f"is_manager: {type(is_manager)}")
print(f"experience: {type(experience)}")
print(f"department: {type(department)}")
print(f"rating: {type(rating)}")
print(f"has_bonus: {type(has_bonus)}")